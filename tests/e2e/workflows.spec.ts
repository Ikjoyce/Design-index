import { expect, test } from '@playwright/test';
import { imageFixture } from '../helpers.js';

test('edits, renames, and retires vocabulary without spending allowance or losing manual labels', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Vocabulary', exact: true }).click();
  const settings = page.getByRole('region', { name: 'Controlled vocabulary', exact: true });
  await expect(settings).toBeVisible();
  const before = await page.evaluate(async () => (await fetch('/api/ai')).json());
  const style = settings.getByRole('textbox', { name: 'style vocabulary', exact: true });
  await style.fill(`${await style.inputValue()}\nswiss-editorial`);
  await settings.getByRole('button', { name: 'Save vocabulary', exact: true }).click();
  await expect(settings.getByRole('status')).toContainText('Vocabulary saved.');

  await page.getByLabel('Title / optional').fill('Vocabulary reference');
  await page.getByLabel('Choose reference image').setInputFiles({ name: 'vocabulary-reference.png', mimeType: 'image/png', buffer: await imageFixture('#4C6A81') });
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await dialog.getByRole('combobox', { name: 'Manual label value' }).selectOption('swiss-editorial');
  await dialog.getByRole('button', { name: 'Add label', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Accept swiss-editorial', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Close reference', exact: true }).click();

  await settings.getByRole('combobox', { name: 'Source label', exact: true }).selectOption('swiss-editorial');
  await settings.getByRole('textbox', { name: 'Target label', exact: true }).fill('swiss-modern');
  page.once('dialog', (confirmation) => confirmation.accept());
  await settings.getByRole('button', { name: 'Rename / merge label', exact: true }).click();
  await expect(settings.getByRole('status')).toContainText('Label renamed/merged.');
  await page.getByRole('combobox', { name: 'Filter label', exact: true }).selectOption('swiss-modern');
  await expect(page.getByRole('button', { name: 'Open Vocabulary reference', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Clear label filter', exact: true }).click();

  await style.fill((await style.inputValue()).split('\n').filter((term) => term !== 'swiss-modern').join('\n'));
  await settings.getByRole('button', { name: 'Save vocabulary', exact: true }).click();
  await expect(settings.getByRole('status')).toContainText('Vocabulary saved.');
  await expect(settings.getByText(/Retired but preserved on existing items: swiss-modern/)).toBeVisible();
  await page.getByRole('combobox', { name: 'Filter label', exact: true }).selectOption('swiss-modern');
  await page.getByRole('button', { name: 'Open Vocabulary reference', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Accept swiss-modern', exact: true })).toBeDisabled();
  await expect(dialog.locator('.label-chip')).toContainText('retired');
  await dialog.getByRole('button', { name: 'Close reference', exact: true }).click();
  const after = await page.evaluate(async () => (await fetch('/api/ai')).json());
  expect(after.usage.calls).toBe(before.usage.calls);
  expect(after.settings.allowImageSharing).toBe(false);
  await page.getByRole('button', { name: 'Clear label filter', exact: true }).click();
  await page.getByRole('button', { name: 'Dark mode', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('vocabulary-dark-mobile.png'), fullPage: true });
});

test('generates variant tabs on demand, preserves drafts, and restores immutable saved revisions', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByLabel('Title / optional').fill('Prompt workflow reference');
  await page.getByLabel('Choose reference image').setInputFiles({ name: 'prompt-workflow.png', mimeType: 'image/png', buffer: await imageFixture('#6D4D83') });
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: 'Close reference', exact: true }).click();
  await page.getByRole('button', { name: 'AI settings', exact: true }).click();
  await page.getByRole('combobox', { name: 'Analyze model', exact: true }).selectOption('claude-haiku-5-5');
  await page.getByRole('combobox', { name: 'Write-prompt model', exact: true }).selectOption('claude-haiku-5-5');
  await page.getByLabel(/I allow normalized screenshots/).check();
  await page.getByRole('button', { name: 'Save AI settings', exact: true }).click();
  await expect(page.getByText('AI settings saved.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Open Prompt workflow reference', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Copy prompt', exact: true })).toBeVisible({ timeout: 20_000 });
  const originalAgent = await dialog.getByRole('textbox', { name: 'Design-language prompt', exact: true }).inputValue();
  expect(originalAgent).toContain('## Tokens');
  await dialog.getByRole('button', { name: 'Edit prompt', exact: true }).click();
  await dialog.getByRole('textbox', { name: 'Design-language prompt', exact: true }).fill('An unsaved agent draft to preserve across tabs.');
  await dialog.getByRole('tab', { name: 'Design tool', exact: true }).click();
  page.once('dialog', (confirmation) => confirmation.accept());
  await dialog.getByRole('button', { name: 'Generate design tool prompt (Go)', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Copy prompt', exact: true })).toBeVisible({ timeout: 10_000 });
  const general = await dialog.getByRole('textbox', { name: 'Design-language prompt', exact: true }).inputValue();
  expect(general).toContain('General design direction');
  expect(general).not.toContain('## Tokens');

  await dialog.getByRole('tab', { name: /Coding agent/ }).click();
  await expect(dialog.getByRole('textbox', { name: 'Design-language prompt', exact: true })).toHaveValue('An unsaved agent draft to preserve across tabs.');
  await dialog.getByRole('button', { name: 'Copy prompt', exact: true }).click();
  expect((await page.evaluate(() => navigator.clipboard.readText())).replaceAll('\r\n', '\n')).toBe(originalAgent);
  await dialog.getByRole('button', { name: 'Save prompt revision', exact: true }).click();
  await expect(dialog.getByRole('status')).toHaveText('New prompt revision saved.');
  const beforeRestore = await page.evaluate(async () => (await fetch('/api/ai')).json());
  await dialog.getByRole('button', { name: 'Version history', exact: true }).click();
  const history = dialog.getByRole('region', { name: 'Coding agent version history', exact: true });
  await history.locator('summary').filter({ hasText: /^v1 ·/ }).click();
  await history.getByRole('button', { name: 'Restore agent revision v1', exact: true }).click();
  await expect(dialog.getByRole('status')).toHaveText('Prompt revision restored as a new saved version.');
  await dialog.getByRole('button', { name: 'Copy prompt', exact: true }).click();
  expect((await page.evaluate(() => navigator.clipboard.readText())).replaceAll('\r\n', '\n')).toBe(originalAgent);
  const afterRestore = await page.evaluate(async () => (await fetch('/api/ai')).json());
  expect(afterRestore.usage.calls).toBe(beforeRestore.usage.calls);

  await dialog.getByRole('tab', { name: 'Vibe', exact: true }).click();
  page.once('dialog', (confirmation) => confirmation.accept());
  await dialog.getByRole('button', { name: 'Generate vibe prompt (Go)', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Copy prompt', exact: true })).toBeVisible({ timeout: 10_000 });
  const vibe = await dialog.getByRole('textbox', { name: 'Design-language prompt', exact: true }).inputValue();
  expect(vibe.split(/\s+/).length).toBeLessThanOrEqual(80);
  expect(vibe).not.toContain('```');
  await dialog.getByRole('button', { name: 'Copy prompt', exact: true }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(vibe);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('prompt-variants-mobile.png'), fullPage: true });
  await dialog.getByRole('button', { name: 'Close reference', exact: true }).click();
  await page.getByLabel(/I allow normalized screenshots/).uncheck();
  await page.getByRole('button', { name: 'Save AI settings', exact: true }).click();
});
