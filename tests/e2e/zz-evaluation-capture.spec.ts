import { expect, test } from '@playwright/test';

test('captures URLs locally, switches views, and enforces local-origin permissions', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Browser capture', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Capture a page', exact: true });
  await panel.getByLabel('Page URL', { exact: true }).fill('http://169.254.169.254');
  await panel.getByRole('button', { name: 'Capture URL', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('blocked');
  await panel.getByText('Local dev-server permissions', { exact: true }).click();
  await panel.getByLabel('Approved local origins').fill('http://localhost:4317');
  await panel.getByRole('button', { name: 'Save capture permissions', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('library');
  await panel.getByLabel('Approved local origins').fill('http://localhost:3000');
  await panel.getByRole('button', { name: 'Save capture permissions', exact: true }).click();
  await expect(panel.getByRole('status')).toContainText('approvals saved');
  await panel.getByLabel('Page URL', { exact: true }).fill('https://capture-fixture.example/design');
  await panel.getByLabel('Capture title', { exact: true }).fill('URL evaluation specimen');
  await panel.getByLabel('Capture note', { exact: true }).fill('CSS facts and responsive views');
  await panel.getByLabel('Site appearance').selectOption('dark');
  const before = await page.evaluate(async () => (await fetch('/api/ai')).json());
  await panel.getByRole('button', { name: 'Capture URL', exact: true }).click();
  const dialog = page.getByRole('dialog'); await expect(dialog).toBeVisible({ timeout: 10_000 });
  await expect(dialog.getByLabel('Title', { exact: true })).toHaveValue('URL evaluation specimen');
  await expect(dialog.getByText('1,440 × 1,000 px', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Mobile', exact: true }).click();
  await expect(dialog.getByText('390 × 844 px', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Full page', exact: true }).click();
  await expect(dialog.getByText('1,440 × 2,200 px', { exact: true })).toBeVisible();
  await dialog.getByText('Captured page facts', { exact: true }).click();
  await expect(dialog.getByText('Fonts: Arial', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('url-capture-mobile.png'), fullPage: true });
  await dialog.getByRole('button', { name: 'Close reference', exact: true }).click();
  const after = await page.evaluate(async () => (await fetch('/api/ai')).json());
  expect(after.usage.calls).toBe(before.usage.calls); expect(after.settings.allowImageSharing).toBe(false);
  expect(errors).toEqual([]);
});

test('hand-labels a reference, runs a synthetic bake-off, and exports without replacing library intelligence', async ({ page }, testInfo) => {
  test.setTimeout(60_000);
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Evaluation tools', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Evaluation lab', exact: true });
  await panel.getByLabel('Find evaluation reference', { exact: true }).fill('URL evaluation specimen');
  const select = panel.getByRole('combobox', { name: 'Evaluation reference', exact: true });
  await expect(select.locator('option')).toHaveCount(2);
  await select.selectOption({ label: 'URL evaluation specimen' });
  await expect(panel.getByLabel('Ground truth style: minimal', { exact: true })).not.toBeChecked();
  await expect(panel.getByRole('button', { name: 'Save hand labels', exact: true })).toBeDisabled();
  await panel.getByLabel('Score style facet', { exact: true }).check();
  await panel.getByLabel('Ground truth style: minimal', { exact: true }).check();
  await panel.getByLabel('Evaluation annotation', { exact: true }).fill('Private synthetic human annotation');
  await panel.getByRole('button', { name: 'Save hand labels', exact: true }).click();
  await expect(panel.getByRole('status')).toContainText('Hand labels saved locally');
  const id = await select.inputValue();

  await page.getByRole('button', { name: 'AI settings', exact: true }).click();
  await page.getByLabel(/I allow normalized screenshots/).check();
  await page.getByRole('button', { name: 'Save AI settings', exact: true }).click();
  await expect.poll(async () => page.evaluate(async (id) => (await (await fetch(`/api/items/${id}`)).json()).intelligence.prompt !== null, id), { timeout: 25_000 }).toBe(true);
  const before = await page.evaluate(async (id) => (await fetch(`/api/items/${id}`)).json(), id);
  await panel.getByLabel('Evaluate model Claude Haiku 5.5', { exact: true }).check();
  await panel.getByLabel('Evaluate model DeepSeek V4.1 Flash', { exact: true }).check();
  await panel.getByLabel('Evaluation run name', { exact: true }).fill('Synthetic two-model comparison');
  await panel.getByLabel(/I authorize these evaluation model calls/).check();
  page.once('dialog', (confirmation) => confirmation.accept());
  await panel.getByRole('button', { name: 'Start evaluation', exact: true }).click();
  const results = panel.getByRole('region', { name: 'Evaluation results', exact: true });
  await expect(results.getByText('completed', { exact: true })).toBeVisible({ timeout: 15_000 });
  await expect(results.locator('tbody tr')).toHaveCount(2);
  const after = await page.evaluate(async (id) => (await fetch(`/api/items/${id}`)).json(), id);
  expect(after.intelligence).toEqual(before.intelligence);
  const downloadEvent = page.waitForEvent('download');
  await results.getByRole('link', { name: 'Export evaluation JSON', exact: true }).click();
  const download = await downloadEvent; const stream = await download.createReadStream(); const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const report = JSON.parse(Buffer.concat(chunks).toString());
  expect(report.snapshots).toHaveLength(2); expect(report.run.status).toBe('completed');
  expect(report.snapshots[0].input.item.manual_labels).toEqual([]);
  expect(JSON.stringify(report.snapshots[0].input)).not.toContain('Private synthetic human annotation');
  await page.getByRole('button', { name: 'Dark mode', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('evaluation-dark-mobile.png'), fullPage: true });
  await page.getByLabel(/I allow normalized screenshots/).uncheck();
  await page.getByRole('button', { name: 'Save AI settings', exact: true }).click();
  expect(errors).toEqual([]);
});
